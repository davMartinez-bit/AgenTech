_TIPOS = [(re.compile(patron), sirve, pide) for patron, sirve, pide in TIPOS]


def normalizar(nombre):
    sin_tildes = "".join(c for c in unicodedata.normalize("NFD", nombre) if unicodedata.category(c) != "Mn")
    return " ".join(sin_tildes.lower().split())


def descripcion_curada(nombre):
    """Descripción revisada del producto, o None si su nombre no calza con ningún tipo."""
    n = normalizar(nombre)
    for patron, sirve, pide in _TIPOS:
        if patron.search(n):
            return (f"Sirve para {sirve}. " if sirve else "") + f"Se pide como: {pide}."
    return None


def por_confirmar(nombre):
    """True si el producto calza con un tipo que todavía hay que confirmar con la ferretería."""
    n = normalizar(nombre)
    for patron, sirve, _ in _TIPOS:
        if patron.search(n):
            return not sirve
    return False
