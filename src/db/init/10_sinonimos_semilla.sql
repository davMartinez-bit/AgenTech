-- Tres tipos de regla:
--   escritura  errores de tipeo y abreviaturas ("wincha" -> "huincha", "pa" -> "para").
--   sinonimo   otro nombre del producto: chilenismos ("galletera"), marcas usadas como genérico ("agorex"),
