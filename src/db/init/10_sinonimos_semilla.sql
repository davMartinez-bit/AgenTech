--
-- Cómo escribir una regla:
--   - frase: en minúsculas, sin tildes ni signos. Basta el singular: "arandela" también calza "arandelas".
--   - equivale: las palabras con que el producto aparece en el catálogo. Si el catálogo usa dos nombres
--     para lo mismo, van los dos ("cuerina pu"). En las de relleno va vacío.
--   - Una frase larga gana a una corta: "abrazadera cremallera" se protege de la regla "cremallera".
--   - Después de agregar reglas: SELECT * FROM revisar_sinonimos(); muestra las que no encuentran
--     productos o esconden más de los que muestran.
-- El ON CONFLICT permite volver a ejecutar el archivo. Las frases que aparezcan en "Lo que buscan y no
-- encuentran" del panel se agregan aquí.
